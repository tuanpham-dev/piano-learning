const URL = 'http://127.0.0.1:5317'
export default async ({ page, shot, log }) => {
  await page.goto(URL)
  await page.waitForSelector('text=Welcome')
  await shot('p1-welcome')
  await page.fill('#welcome-name', 'Linh')
  await page.click("text=I'm a kid")
  await page.click("text=Let's play")
  await page.waitForURL(URL + '/')
  await page.waitForTimeout(600)
  await shot('p1-kid-home')
  log('kid home header:', await page.textContent('h1'))
  await page.reload()
  await page.waitForTimeout(800)
  log('after reload url:', page.url(), 'h1:', await page.textContent('h1'))
  await page.goto(URL + '/settings')
  await page.click('text=Adult')
  await page.click('text=Tiếng Việt')
  await page.waitForTimeout(300)
  await shot('p1-settings-vi')
  await page.goto(URL + '/')
  await page.waitForTimeout(500)
  await shot('p1-adult-home-vi')
  log('adult home tiles:', (await page.locator('main a').allTextContents()).join(' | '))
  // Free play: click, keyboard and virtual MIDI paths
  await page.goto(URL + '/settings')
  await page.click('text=English')
  for (let i = 0; i < 5; i++) await page.click('text=Version 1.0.0')
  await page.goto(URL + '/free')
  await page.waitForTimeout(500)
  await shot('p1-free')
  const ctxState = await page.evaluate(() => 1)
  log(ctxState)
}
