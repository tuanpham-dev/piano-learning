const URL = 'http://127.0.0.1:5317'
export default async ({ page, shot, log }) => {
  await page.goto(URL)
  await page.click("text=I'm an adult"); await page.click("text=Let's play")
  await page.goto(URL + '/songs/import')
  await page.setInputFiles('#import-file', 'src/engine/__fixtures__/two-track.mid')
  await page.waitForSelector('[data-testid=mapping]')
  log('mapping:', (await page.locator('[data-testid=mapping]').innerText()).replace(/\n/g, ' | '))
  await shot('a16-mapping')
  await page.click('text=Add to library')
  await page.waitForSelector('.staff-host svg')
  log('url after add:', page.url().replace(URL, ''))
  await page.click('text=▶ Start'); await page.waitForTimeout(400)
  log('status:', await page.evaluate(() => window.__pa.status), 'due', await page.evaluate(() => window.__pa.dueMidis()))
  await shot('a16-imported-play')
  await page.reload(); await page.waitForTimeout(800)
  await page.goto(URL + '/songs')
  await page.click('text=Imported')
  log('imported after reload:', (await page.locator('[data-song]').allInnerTexts()).map((s) => s.replace(/\n/g, ' ')))
  await page.goto(URL + '/songs/import')
  await page.setInputFiles('#import-file', 'src/engine/__fixtures__/empty.mid')
  await page.waitForSelector('[role=alert]')
  log('empty:', await page.locator('[role=alert]').innerText(), '| mapping shown:', await page.locator('[data-testid=mapping]').count())
}
